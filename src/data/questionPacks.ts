// Local Storage Keys
const STORAGE_KEYS = {
  CUSTOM_QUESTIONS: 'health_balance_custom_questions_v1',
  PURCHASED_PACKS: 'health_balance_purchased_packs_v1',
};

export function loadCustomQuestions(): QuestionDBItem[] {
  if (typeof window === 'undefined') return [];
  try {
    const raw = localStorage.getItem(STORAGE_KEYS.CUSTOM_QUESTIONS);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed)) return parsed;
    }
  } catch (e) {
    console.error('Failed to load custom questions from storage', e);
  }
  return [];
}

export function saveCustomQuestions(questions: QuestionDBItem[]): void {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(STORAGE_KEYS.CUSTOM_QUESTIONS, JSON.stringify(questions));
  } catch (e) {
    console.error('Failed to save custom questions', e);
  }
}

