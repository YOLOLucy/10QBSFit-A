const LANG_STORAGE_KEY = 'health_balance_language_v1';

export function getStoredLanguage(): AppLanguage {
  try {
    const saved = localStorage.getItem(LANG_STORAGE_KEY) as AppLanguage;
    if (saved && TRANSLATIONS[saved]) return saved;
  } catch (e) {
    // Ignore
  }
  return 'zh-TW';
}

export function saveStoredLanguage(lang: AppLanguage): void {
  try {
    localStorage.setItem(LANG_STORAGE_KEY, lang);
  } catch (e) {
    // Ignore
  }
}

export function translate(key: string, currentLang?: AppLanguage | string, fallback?: string): string {
  const langKey = (currentLang as AppLanguage) || 'zh-TW';
  const dict = TRANSLATIONS[langKey] || TRANSLATIONS['zh-TW'];
  if (dict && dict[key]) return dict[key];
  if (TRANSLATIONS['zh-TW'] && TRANSLATIONS['zh-TW'][key]) return TRANSLATIONS['zh-TW'][key];
  return fallback || key;
}
